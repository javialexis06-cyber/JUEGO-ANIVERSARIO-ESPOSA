def exportar():
    bpy.ops.object.select_all(action='SELECT')
    bpy.ops.object.delete(use_global=False)
    coll = bpy.data.collections.new('Autoría de poses del Torneo')
    bpy.context.scene.collection.children.link(coll)
    # Solo los huesos de combate, con la misma jerarquía y orientación del rig compartido.
    # No importar constructores de mallas: exportar poses no necesita marching cubes.
    layout = {'raiz': (0, 0, 0), 'pelvis': (0, .03, .47), 'torso': (0, .03, .60), 'cabeza': (0, .02, .90)}
    for lado, signo in [('L', -1), ('R', 1)]:
        layout.update({f'brazo.{lado}': (signo*.32, .04, .79), f'mano.{lado}': (signo*.47, .075, .59),
                       f'pierna.{lado}': (signo*.235, .03, .42), f'pie.{lado}': (signo*.235, -.01, .15)})
    arm = rig.build_armature('Torneo', layout, coll)
    arm.animation_data_create()
    salida = {}
    for nombre, pose in POSES.items():
        for pb in arm.pose.bones:
            pb.rotation_mode = 'XYZ'
            pb.rotation_euler = (0, 0, 0)
            pb.scale = (1, 1, 1)
        for hueso, grados in pose['huesos'].items():
            pb = arm.pose.bones[hueso]
            pb.rotation_euler = Euler(tuple(math.radians(v) for v in grados), 'XYZ')
        for hueso, factor in pose.get('estira', {}).items():
            arm.pose.bones[hueso].scale = (1, factor, 1)
        action = bpy.data.actions.new('torneo_' + nombre)
        arm.animation_data.action = action
        for pb in arm.pose.bones:
            pb.keyframe_insert('rotation_euler', frame=1)
            pb.keyframe_insert('scale', frame=1)
        bpy.context.view_layer.update()
        rotaciones = {}
        for hueso in pose['huesos']:
            q = arm.pose.bones[hueso].matrix_basis.to_quaternion()
            rotaciones[hueso] = [round(q.x, 8), round(q.y, 8), round(q.z, 8), round(q.w, 8)]
        salida[nombre] = {'q': rotaciones, 'y': pose.get('y', 0), 'estira': pose.get('estira', {})}
    ruta = HERE.parent.parent / 'juego/web/src/peleas/poses-blender.json'
    ruta.write_text(json.dumps(salida, ensure_ascii=False, separators=(',', ':')) + '\n')
    print(f'OK {len(salida)} poses del Torneo horneadas desde Blender → {ruta.name}')


if __name__ == '__main__':
    exportar()
