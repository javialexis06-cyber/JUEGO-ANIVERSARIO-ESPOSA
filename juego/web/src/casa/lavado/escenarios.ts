// Los escenarios y sus oleadas minuto a minuto, como en el original: cada minuto dice cuántos mugrosos tiene que
// haber como mínimo en pantalla (si hay menos, llegan de golpe), cada cuánto aparece una tanda (uno de cada tipo
// de la lista) y qué tipos salen. Encima, eventos a minutos fijos: enjambres que cruzan, anillos que se cierran,
// muros, élites que sueltan cofre y jefes. A los 30:00 llega la Ducha Helada.
import type { IdEnemigo, IdEscenario } from './tipos';

export interface Oleada {
  /** Mínimo en pantalla. */
  min: number;
  /** Segundos entre tandas. */
  cada: number;
  tipos: IdEnemigo[];
}

export type TipoEvento = 'jefe' | 'elite' | 'enjambre' | 'anillo' | 'muro' | 'carta' | 'flotar';

export interface EventoOleada {
  /** Segundo de la partida. */
  t: number;
  tipo: TipoEvento;
  enemigo: IdEnemigo;
  cant?: number;
  aviso?: string;
}

export interface DefEscenario {
  id: IdEscenario;
  nombre: string;
  original: string;
  desc: string;
  /** Pasillo (como la biblioteca): el mapa tiene techo y piso. */
  limites: { yMin: number; yMax: number } | null;
  /** Pasillo de arriba abajo (como la torre): paredes a la izquierda y a la derecha. */
  limitesX?: { xMin: number; xMax: number };
  oleadas: Oleada[];
  eventos: EventoOleada[];
  /** Cómo se gana. */
  desbloqueo: string;
  /** El jefe del minuto 25: vencerlo abre el modo Hiper de este escenario. */
  jefeHiper: IdEnemigo;
  /** La Ducha: chorros de agua que caen del techo y empujan a todos. */
  chorros?: boolean;
  /** La Jabonera: frascos que se caen de la repisa (avisan con su sombra; al caer pegan a todos, también a ti). */
  frascos?: boolean;
  /** El Desagüe: remolinos que se tragan a los mugrosos (y las gotitas que nadie recoja). */
  remolinos?: boolean;
  /** Los especiales duran menos (en segundos; si no, 30 minutos) y salen aparte en el menú. */
  duracion?: number;
  especial?: boolean;
  /** El Espejo empañado: el vapor tapa la vista y lo caliente pega más. */
  vapor?: boolean;
  calientes?: boolean;
  /** El Desfile de jefes: los jefes llegan uno tras otro, así que tienen menos vida y dan más experiencia. */
  vidaJefes?: number;
  xpJefes?: number;
  /** El Tobogán: la corriente que lleva a todos hacia adelante (unidades por segundo). */
  tobogan?: number;
  /** Cuánto pegan los mugrosos al tocarlo a uno (en el tobogán, menos: no hay para dónde huir). */
  danoBichos?: number;
  /** El Laberinto de la cortina: las cortinas de `laberinto.ts` atajan a los jugadores. */
  laberinto?: boolean;
  /** Los mugrosos salen grandotes (más grandes, con más vida y el doble de experiencia). */
  grandes?: boolean;
}

